int
msdos_cp437_to_utf8(unsigned char c, char *out)
{
    unsigned u = cp437[c];
    if (u < 0x80) {
        out[0] = (char) u;
        out[1] = 0;
        return 1;
    }
    if (u < 0x800) {
        out[0] = (char) (0xC0 | (u >> 6));
        out[1] = (char) (0x80 | (u & 0x3F));
        out[2] = 0;
        return 2;
    }
    out[0] = (char) (0xE0 | (u >> 12));
    out[1] = (char) (0x80 | ((u >> 6) & 0x3F));
    out[2] = (char) (0x80 | (u & 0x3F));
    out[3] = 0;
    return 3;
}

int
msdos_utf8_to_cp437(unsigned cp)
{
    if (cp >= 0x20 && cp < 0x7F)
        return (int) cp;
    for (int i = 1; i < 256; i++)
        if (cp437[i] == cp && i != 0x20)
            return i;
    return -1;
}

int
msdos_screen_text(char *dst, int dstsz)
{
    if (!dst || dstsz <= 0)
        return 0;
    dst[0] = 0;

    const uint8_t mode = mem_readb_phys(0x449);
    if (mode > 3 && mode != 7)
        return -1;
    int cols = mem_readw_phys(0x44A);
    int rows = mem_readb_phys(0x484) + 1;
    if (cols < 40 || cols > 132)
        cols = (mode <= 1) ? 40 : 80;
    if (rows < 25 || rows > 60)
        rows = 25;
    const uint32_t base = (mode == 7 ? 0xB0000 : 0xB8000) + mem_readw_phys(0x44E);

    int len = 0;
    for (int r = 0; r < rows; r++) {
        int line_start = len;
        int last_nonblank = len;
        for (int c = 0; c < cols; c++) {
            char    u[4];
            uint8_t ch = mem_readb_phys(base + (uint32_t) (r * cols + c) * 2);
            int     n  = msdos_cp437_to_utf8(ch, u);
            if (len + n + 2 >= dstsz)
                goto done;
            memcpy(dst + len, u, (size_t) n);
            len += n;
            if (ch != 0x20 && ch != 0x00 && ch != 0xFF)
                last_nonblank = len;
        }
        len = last_nonblank > line_start ? last_nonblank : line_start;
        dst[len++] = '\n';
    }
done:
    dst[len] = 0;
    return len;
}
