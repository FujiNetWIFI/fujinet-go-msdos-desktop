#!/usr/bin/env python3
"""Build the FujiNet boot floppies the app carries, as a C source to embed.

    make-boot-floppy.py --freedos DIR --fujinet-sys FILE [--autorun IMG]
                        --out-c FILE [--out-dir DIR]
    make-boot-floppy.py --freedos DIR --plain-out IMG

One image per drive size (360K for 5.25" drives, 720K, 1.44M for 3.5"):
FreeDOS (boot sector, KERNEL.SYS, COMMAND.COM), FUJINET.SYS, and the FujiNet
DOS programs from the firmware's RS232 autorun.img (CONFIG.EXE, FMOUNT, ...).
AUTOEXEC.BAT runs CONFIG, as the autorun disk does.

CONFIG.SYS has a fixed size and place on each image so the app can rewrite
it in place (bootdisk.c) when the COM port or speed changes; its default
says COM2 at 115200.

The C file holds each image as runs of non-zero sectors.

--plain-out writes a 360K FreeDOS floppy with nothing of FujiNet's on it,
which boots straight to the A: prompt (the tests type at it).

Copyright (C) 2026 Thomas Cherryhomes
SPDX-License-Identifier: GPL-3.0-or-later
"""

import argparse
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import fat12  # noqa: E402

CONFIG_SYS_SIZE = 384
IMAGES = (("360", 360), ("720", 720), ("1440", 1440))


def config_sys(port=2, bps=115200):
    """The CONFIG.SYS text, padded to CONFIG_SYS_SIZE (bootdisk.c makes the
    same text; keep them in step)."""
    text = ("DEVICE=FUJINET.SYS FUJI_PORT=%d FUJI_BPS=%d\r\n"
            "DEVICE=FUJIPRN.SYS\r\n"
            "LASTDRIVE=Z\r\n"
            "FILES=20\r\n"
            "BUFFERS=20\r\n" % (port, bps))
    # Padded with REM lines DOS will take (FreeDOS refuses long lines).
    while len(text) < CONFIG_SYS_SIZE:
        room = CONFIG_SYS_SIZE - len(text)
        if room < 5:
            text += " " * room
            break
        n = min(64, room) - 2
        text += ("REM" + " " * (n - 3))[:n] + "\r\n"
    return text.encode("ascii")


def kernel_quiet(kernel):
    """No F5/F8 prompt and no drive-assignment listing: the kernel's own
    CONFIG block (what SYS CONFIG edits)."""
    k = bytearray(kernel)
    i = k.find(b"CONFIG")
    if i < 0 or i > 64:
        raise ValueError("KERNEL.SYS has no CONFIG block")
    k[i + 9] = 0            # InitDiskShowDriveAssignment
    k[i + 10] = 0xFF        # SkipConfigSeconds = -1: no prompt
    return bytes(k)


def files_for(args):
    fd = args.freedos
    with open(os.path.join(fd, "KERNEL.SYS"), "rb") as f:
        kernel = kernel_quiet(f.read())
    with open(os.path.join(fd, "COMMAND.COM"), "rb") as f:
        command = f.read()
    with open(args.fujinet_sys, "rb") as f:
        fujinet = f.read()
    extra = {}
    if args.autorun and os.path.exists(args.autorun):
        with open(args.autorun, "rb") as f:
            extra = fat12.read_files(f.read())
    for drop in ("CONFIG.SYS", "AUTOEXEC.BAT", "FUJINET.SYS"):
        extra.pop(drop, None)
    autoexec = b"@ECHO OFF\r\nCONFIG.EXE\r\n" if "CONFIG.EXE" in extra else b"@ECHO OFF\r\n"
    files = [("KERNEL.SYS", kernel), ("COMMAND.COM", command),
             ("CONFIG.SYS", config_sys()), ("AUTOEXEC.BAT", autoexec),
             ("FUJINET.SYS", fujinet)]
    files += sorted(extra.items())
    return files


def runs(image):
    """(offset, bytes) runs of non-zero 512-byte sectors."""
    out = []
    i = 0
    n = len(image) // 512
    while i < n:
        if image[i * 512:(i + 1) * 512].count(0) == 512:
            i += 1
            continue
        j = i
        while j < n and image[j * 512:(j + 1) * 512].count(0) != 512:
            j += 1
        out.append((i * 512, image[i * 512:j * 512]))
        i = j
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--freedos", required=True)
    ap.add_argument("--fujinet-sys")
    ap.add_argument("--autorun")
    ap.add_argument("--out-c")
    ap.add_argument("--out-dir")
    ap.add_argument("--plain-out")
    args = ap.parse_args()

    with open(os.path.join(args.freedos, "bootsect.bin"), "rb") as f:
        bootsect = f.read()
    if args.plain_out:
        with open(os.path.join(args.freedos, "KERNEL.SYS"), "rb") as f:
            kernel = kernel_quiet(f.read())
        with open(os.path.join(args.freedos, "COMMAND.COM"), "rb") as f:
            command = f.read()
        image, _ = fat12.build(360, bootsect, [
            ("KERNEL.SYS", kernel), ("COMMAND.COM", command),
            ("CONFIG.SYS", b"FILES=20\r\n"), ("AUTOEXEC.BAT", b"@PROMPT $P$G\r\n")])
        with open(args.plain_out, "wb") as f:
            f.write(image)
        return
    if not args.fujinet_sys or not args.out_c:
        ap.error("--fujinet-sys and --out-c are required")
    files = files_for(args)

    lines = ["/* Generated by tools/disks/make-boot-floppy.py -- do not edit. */",
             "#include \"bootdisk_data.h\"", ""]
    table = []
    for tag, kb in IMAGES:
        image, where = fat12.build(kb, bootsect, files)
        if args.out_dir:
            os.makedirs(args.out_dir, exist_ok=True)
            with open(os.path.join(args.out_dir, f"fujinet-boot-{tag}k.img"), "wb") as f:
                f.write(image)
        cfg_off, cfg_size = where["CONFIG.SYS"]
        rr = runs(image)
        for k, (off, data) in enumerate(rr):
            lines.append(f"static const unsigned char img{tag}_run{k}[{len(data)}] = {{")
            for p in range(0, len(data), 24):
                lines.append("    " + ",".join(str(b) for b in data[p:p + 24]) + ",")
            lines.append("};")
        lines.append(f"static const msdos_bootdisk_run img{tag}_runs[{len(rr)}] = {{")
        for k, (off, data) in enumerate(rr):
            lines.append(f"    {{ {off}u, {len(data)}u, img{tag}_run{k} }},")
        lines.append("};")
        table.append(f"    {{ {kb}, {len(image)}u, {cfg_off}u, {cfg_size}u, img{tag}_runs, {len(rr)} }},")
    lines.append(f"const msdos_bootdisk_image msdos_bootdisk_images[{len(IMAGES)}] = {{")
    lines += table
    lines.append("};")
    lines.append(f"const int msdos_bootdisk_image_count = {len(IMAGES)};")
    names = ", ".join(n for n, _ in files)
    lines.append(f"const char msdos_bootdisk_contents[] = \"{names}\";")
    lines.append("")
    os.makedirs(os.path.dirname(os.path.abspath(args.out_c)), exist_ok=True)
    tmp = args.out_c + ".tmp"
    with open(tmp, "w", encoding="ascii", newline="\n") as f:
        f.write("\n".join(lines))
    os.replace(tmp, args.out_c)


if __name__ == "__main__":
    main()
